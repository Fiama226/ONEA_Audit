#!/bin/sh
# Generates conf.d/realip.conf from TRUSTED_UPSTREAM_CIDRS (comma- or space-separated IPs/CIDRs
# of load balancers / proxies placed IN FRONT of nginx). Empty = disabled (default): nginx
# then uses the TCP peer as the client address. When set, X-Forwarded-For is honoured ONLY
# when the TCP peer belongs to one of these ranges; the real client is the right-most address
# that is not itself a trusted upstream (real_ip_recursive). Runs from /docker-entrypoint.d
# before the templates are rendered.
set -eu
out=/etc/nginx/conf.d/realip.conf
{
  echo '# generated by 20-realip.sh from TRUSTED_UPSTREAM_CIDRS'
  count=0
  for cidr in $(echo "${TRUSTED_UPSTREAM_CIDRS:-}" | tr ',' ' '); do
    case "$cidr" in
      *[!0-9a-fA-F:./]*) echo "TRUSTED_UPSTREAM_CIDRS: invalid entry '$cidr'" >&2; exit 1 ;;
    esac
    echo "set_real_ip_from $cidr;"
    count=$((count + 1))
  done
  if [ "$count" -gt 0 ]; then
    echo 'real_ip_header X-Forwarded-For;'
    echo 'real_ip_recursive on;'
  fi
} > "$out"
